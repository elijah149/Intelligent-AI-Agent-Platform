from sqlalchemy.orm import Session

from backend.app.models.database import Customer, Incident


# Private capability used only after successful resolution verification.
# Callers cannot simply pass True/False to bypass the verification step.
_RESOLUTION_VERIFICATION_TOKEN = object()


def create_incident(
    db: Session,
    customer_id: int,
    issue: str,
) -> Incident:
    customer = (
        db.query(Customer)
        .filter(Customer.id == customer_id)
        .first()
    )

    if customer is None:
        raise ValueError("Customer not found.")

    incident = Incident(
        customer_id=customer_id,
        issue=issue,
        status="open",
    )

    db.add(incident)
    db.commit()
    db.refresh(incident)

    return incident


def get_incident(
    db: Session,
    incident_id: int,
) -> Incident | None:
    return (
        db.query(Incident)
        .filter(Incident.id == incident_id)
        .first()
    )


def list_incidents(
    db: Session,
    customer_id: int | None = None,
) -> list[Incident]:

    query = db.query(Incident)

    if customer_id is not None:
        query = query.filter(
            Incident.customer_id == customer_id
        )

    return (
        query
        .order_by(Incident.created_at.desc())
        .all()
    )


def update_diagnosis(
    db: Session,
    incident_id: int,
    diagnosis: str,
) -> Incident:

    incident = (
        db.query(Incident)
        .filter(Incident.id == incident_id)
        .first()
    )

    if incident is None:
        raise ValueError("Incident not found.")

    incident.diagnosis = diagnosis
    incident.status = "diagnosed"

    db.commit()
    db.refresh(incident)

    return incident


def close_incident(
    db: Session,
    incident_id: int,
    *,
    verification_token=None,
) -> Incident:
    """
    Close an incident only after successful resolution verification.

    The verification token is a private capability generated by this
    service module. Direct callers cannot close an incident by simply
    passing True/False.
    """

    if verification_token is not _RESOLUTION_VERIFICATION_TOKEN:
        raise PermissionError(
            "Incident cannot be closed without successful "
            "resolution verification."
        )

    incident = (
        db.query(Incident)
        .filter(Incident.id == incident_id)
        .first()
    )

    if incident is None:
        raise ValueError("Incident not found.")

    incident.status = "resolved"

    db.commit()
    db.refresh(incident)

    return incident


def get_resolution_verification_token():
    """
    Return the private capability required to close an incident.

    This function is intentionally not registered as an AI tool.
    """

    return _RESOLUTION_VERIFICATION_TOKEN
